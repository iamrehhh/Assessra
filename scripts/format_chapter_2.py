def process_text(text):
    lines = text.split('\n')
    output = []
    
    in_table = False
    table_lines = []
    
    def render_table(tbl):
        if not tbl: return ""
        # The first line is the header
        header = tbl[0].split('\t')
        
        # Build the table
        out_tbl = []
        out_tbl.append("| " + " | ".join(header) + " |")
        out_tbl.append("|" + "|".join(["---" for _ in header]) + "|")
        for row in tbl[1:]:
            cols = row.split('\t')
            # Pad with empty if some columns are missing
            while len(cols) < len(header):
                cols.append("")
            out_tbl.append("| " + " | ".join(cols) + " |")
            
        return "\n".join(out_tbl) + "\n"

    for line in lines:
        line = line.strip()
        if '\t' in line:
            if not in_table:
                in_table = True
                table_lines = []
            table_lines.append(line)
        else:
            if in_table:
                # But wait, there might be lines without tabs that belong to a table? 
                # If the line is empty, the table ends. 
                # Or if there are no tabs but we are in a table, it could be a single-column row in the table, or the end of the table.
                # Let's assume end of table.
                output.append(render_table(table_lines))
                in_table = False
                table_lines = []
            
            # Now handle normal line
            if not line:
                output.append("")
            else:
                # Is it a title?
                if len(line) < 60 and not line.endswith('.') and not line.endswith('?') and not line.endswith(':') and not line.endswith(','):
                    # Could be a title. Let's make it a header.
                    output.append(f"### {line}")
                else:
                    output.append(line)

    if in_table:
        output.append(render_table(table_lines))
        
    return "\n".join(output)

